# Авторское решение (Dima Roslik):
ex = :(200.0 + 50.0)
println("Тип узла (head): ", ex.head)
println("Аргументы (args): ", ex.args)

# Модифицируем синтаксическое дерево до вычисления:
ex.args[1] = :*
ex.args[3] = 1.25

new_val = eval(ex)
println("Новое выражение: ", ex)
println("Результат расчета: ", new_val)
